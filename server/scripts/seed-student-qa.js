async function main() {
  console.log(`🌱 植入學生 Q&A 種子資料（共 ${qaData.length} 筆）...\n`);

  // 找課程 ID
  const courseRow = await pool.query(`SELECT id FROM courses WHERE name = $1 LIMIT 1`, [COURSE_NAME]);
  const courseId = courseRow.rows[0]?.id ?? null;
  if (!courseId) { console.warn(`⚠️ 找不到課程「${COURSE_NAME}」，course_id 將為 null`); }
  else { console.log(`✅ 課程: ${COURSE_NAME} (${courseId})\n`); }

  const adminUser = await pool.query(`SELECT id FROM users WHERE role = 'admin' LIMIT 1`);
  const createdBy = adminUser.rows[0]?.id ?? null;

  let inserted = 0, skipped = 0;

  for (let i = 0; i < qaData.length; i++) {
    const { category, question, answer } = qaData[i];
    process.stdout.write(`  [${String(i+1).padStart(2)}/${qaData.length}] ${question.slice(0,38)}... `);

    const dup = await pool.query(
      `SELECT id FROM knowledge_qa WHERE question = $1 AND is_active = TRUE LIMIT 1`,
      [question]
    );
    if (dup.rows.length > 0) { console.log('(已存在，跳過)'); skipped++; continue; }

    try {
      await pool.query(
        `INSERT INTO knowledge_qa (course_id, category, question, answer, created_by)
         VALUES ($1, $2, $3, $4, $5)`,
        [courseId, category, question, answer, createdBy]
      );
      console.log('✅');
      inserted++;
    } catch (err) {
      console.log(`❌ ${err.message}`);
    }
  }

  console.log(`\n🎉 完成！插入 ${inserted} 筆，跳過 ${skipped} 筆`);
  console.log(`\n📝 提醒老師：這些答案為草稿，請至「問答管理」頁面審核並修改。`);
  await pool.end();
}

main().catch(err => { console.error('❌', err); process.exit(1); });
